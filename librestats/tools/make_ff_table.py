"""Generate minimum-aberration generators for 2^(k-p) fractional factorials.

For k = 3..11 factors and 4..128 runs (n = k - p basic factors), searches all
sets of p generator columns (interactions of at least two basic factors) for
the design with minimum aberration (Fries & Hunter, 1980): the
lexicographically smallest word-length pattern (A3, A4, ...). Branch and
bound: the word-length pattern of a partial set of generators is a lower
bound for every completion. Ties go to the first set found, with generators
tried from the highest-order interaction down.

The resolutions are checked against the NIST/SEMATECH e-Handbook summary
table of fractional factorial designs (section 5.3.3.4.7).

Usage: python3 tools/make_ff_table.py
Writes src/pythonpath/librestats/ff_table.py.
"""

import itertools
import os
import sys
import time

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "pythonpath", "librestats",
                   "ff_table.py")
LETTERS = "ABCDEFGHJKLMNOPQRSTUVWXYZ"   # no I, as is usual (I is the identity)
MAX_BASE = 7                            # up to 2^7 = 128 runs

# NIST e-Handbook 5.3.3.4.7: (k, runs) -> resolution
NIST = {(3, 4): 3, (4, 8): 4, (5, 16): 5, (5, 8): 3, (6, 32): 6, (6, 16): 4, (6, 8): 3,
        (7, 64): 7, (7, 32): 4, (7, 16): 4, (7, 8): 3, (8, 128): 8, (8, 64): 5, (8, 32): 4,
        (8, 16): 4, (9, 128): 6, (9, 64): 4, (9, 32): 4, (9, 16): 3, (10, 128): 5,
        (10, 64): 4, (10, 32): 4, (10, 16): 3, (11, 128): 5, (11, 64): 4, (11, 32): 4,
        (11, 16): 3}


def search(k, n):
    p = k - n
    cands = sorted((c for c in range(1, 1 << n) if bin(c).count("1") >= 2),
                   key=lambda c: (-bin(c).count("1"), c))
    best = [None, None]   # wlp, generators

    def extend(chosen, words, start):
        # words: list of (basic-factor mask, number of generators) of the subgroup
        wlp = [0] * (k + 1)
        for mask, g in words:
            wlp[bin(mask).count("1") + g] += 1
        if best[0] is not None and wlp > best[0]:
            return
        if len(chosen) == p:
            if best[0] is None or wlp < best[0]:
                best[0], best[1] = wlp, list(chosen)
            return
        for i in range(start, len(cands)):
            c = cands[i]
            new = [(c, 1)] + [(m ^ c, g + 1) for m, g in words]
            extend(chosen + [c], words + new, i + 1)

    extend([], [], 0)
    return best


def name(mask):
    return "".join(LETTERS[i] for i in range(MAX_BASE) if mask >> i & 1)


def main():
    rows, problems = [], []
    for k in range(3, 12):
        for n in range(2, min(k, MAX_BASE + 1)):
            if (1 << n) < k + 1:      # resolution III needs at least k + 1 runs
                continue
            t = time.time()
            wlp, gens = search(k, n)
            resolution = next(length for length, count in enumerate(wlp) if count)
            runs = 1 << n
            ref = NIST.get((k, runs))
            if ref is not None and ref != resolution:
                problems.append(f"2^({k}-{k - n}): resolution {resolution}, NIST {ref}")
            print(f"2^({k}-{k - n}) {runs:4d} runs  res {resolution}  "
                  f"{' '.join(LETTERS[n + j] + '=' + name(g) for j, g in enumerate(gens))}  "
                  f"wlp {wlp[3:]}  ({time.time() - t:.1f} s)", flush=True)
            rows.append((k, runs, resolution, tuple(name(g) for g in gens), tuple(wlp[3:])))
    missing = set(NIST) - {(k, r) for k, r, *_ in rows}
    problems += [f"NIST design {m} not generated" for m in sorted(missing)]
    if problems:
        print("\n".join(problems))
        sys.exit(1)

    with open(OUT, "w") as f:
        f.write('"""Minimum-aberration generators of 2^(k-p) fractional factorial designs.\n\n'
                "GENERATED by tools/make_ff_table.py - do not edit by hand.\n"
                "Exhaustive search for the lexicographically smallest word-length pattern\n"
                "(Fries & Hunter, 1980); resolutions agree with the NIST/SEMATECH\n"
                "e-Handbook table 5.3.3.4.7. Generator j defines the (n + j)-th factor as the\n"
                'product of the listed basic factors (letters skip I).\n"""\n\n')
        f.write("# (factors, runs): (resolution, generators, word-length pattern A3, A4, ...)\n")
        f.write("DESIGNS = {\n")
        for k, runs, res, gens, wlp in rows:
            f.write(f"    ({k}, {runs}): ({res}, {gens!r}, {wlp!r}),\n")
        f.write("}\n")
    print(f"Wrote {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
